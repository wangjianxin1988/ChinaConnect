import fs from "node:fs";
const path = "src/i18n/translations.ts";
let s = fs.readFileSync(path, "utf8").replace(/\r\n/g, "\n");
const re = /(noPosts: "[^"]*")\n(\s+backToList:)/g;
const before = (s.match(/noPosts:/g) || []).length;
s = s.replace(re, "$1,\n$2");
const after = (s.match(/noPosts:/g) || []).length;
console.log("noPosts before:", before, "after:", after, "fixed count:", (s.match(/noPosts: "[^"]*",\n\s+backToList:/g) || []).length);
const tmp = path + ".tmp";
fs.writeFileSync(tmp, s);
fs.renameSync(tmp, path);
