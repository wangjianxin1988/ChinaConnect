import fs from "node:fs";
const p = "src/i18n/translations.ts";
let s = fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const re = /(blog: "[^"]*")(\n\s{6}business:)/g;
let count = 0;
s = s.replace(re, (m, a, b) => { count++; return a + "," + b; });
const tmp = p + ".tmp";
fs.writeFileSync(tmp, s);
fs.renameSync(tmp, p);
console.log("commas fixed:", count);
