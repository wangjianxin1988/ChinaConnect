/** Translate an account/subscription UI key into the given language (falls back to en). */
export function accountT(
  lang: string,
  key: AccountKey,
  vars?: Record<string, string | number>,
): string {
  const l = (ACCOUNT_LANGS as string[]).includes(lang) ? (lang as AccountLang) : "en";
  let v: string = ACCOUNT_STRINGS[key]?.[l] ?? ACCOUNT_STRINGS[key]?.en ?? "";
  if (vars) {
    v = v.replace(/\{(\w+)\}/g, (_m, k) => (k in vars ? String(vars[k]) : "{" + k + "}"));
  }
  return v;
}

/** Map any site language code to a valid AccountLang (invalid -> en). */
export function toAccountLang(lang: string): AccountLang {
  return (ACCOUNT_LANGS as string[]).includes(lang) ? (lang as AccountLang) : "en";
}

/** Build a language-prefixed internal path (e.g. /ja/pricing; en stays unprefixed). */
export function localizedHref(lang: AccountLang | string, path: string): string {
  const l = toAccountLang(lang);
  return l === "en" ? path : `/${l}${path}`;
}
